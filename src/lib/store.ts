export function getStoredJobs(): MediaJob[] {
  if (typeof window === 'undefined') return [SAMPLE_JOB];
  try {
    const raw = localStorage.getItem('repurposeflow_jobs');
    if (!raw) {
      localStorage.setItem('repurposeflow_jobs', JSON.stringify([SAMPLE_JOB]));
      return [SAMPLE_JOB];
    }
    return JSON.parse(raw);
  } catch {
    return [SAMPLE_JOB];
  }
}

export function saveStoredJobs(jobs: MediaJob[]) {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem('repurposeflow_jobs', JSON.stringify(jobs));
  } catch (err) {
    console.error('Failed to persist jobs:', err);
  }
}

